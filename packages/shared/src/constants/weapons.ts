export type FireMode = 'auto' | 'semi' | 'bolt' | 'melee' | 'pump';
export type SecondaryActionType =
  | 'none'
  | 'scope'
  | 'heavy_stab'
  | 'toggle_silencer'
  | 'toggle_burst'
  | 'raise_shield';

export interface WeaponDef {
  id: string;
  name: string;
  category: 'rifle' | 'sniper' | 'pistol' | 'smg' | 'shotgun' | 'melee' | 'grenade' | 'shield';
  slot: 1 | 2 | 3 | 4 | 5; // 1: Primary, 2: Secondary, 3: Melee, 4: Utility, 5: Bomb
  fireMode: FireMode;
  price: number;
  damage: number;
  headDamageMultiplier: number;
  armorPenetration: number; // e.g. 0.775 for 77.5%
  fireRateRpm: number;
  magCapacity: number;
  reserveAmmo: number;
  reloadTime: number;
  movementSpeed: number;
  penetrationPower: number;
  baseSpread: number;
  killReward: number;
  sprayPattern: Array<[number, number]>; // [pitchDeg, yawDeg]

  // Sprint E3 Ballistic & Recoil Control Extensions
  recoilViewPunchScale: number;
  recoveryTimeStand: number;        // Recovery reset time when standing (s)
  recoveryTimeCrouch: number;       // Faster reset when crouching (s)
  crouchSpreadMultiplier: number;   // Spread reduction when crouching (e.g. 0.65x)
  inaccuracyMove: number;           // Move inaccuracy scaling
  inaccuracyJump: number;           // Jump inaccuracy penalty
  inaccuracyFire: number;           // Per-shot tapping inaccuracy bloom
  taggingPower: number;             // Speed fraction retained on hit (0.45 to 0.75)
  damageDropoffPer10m: number;      // Range damage drop-off multiplier per 10m

  // CS 1.6 Authentic Mechanics Extensions
  pelletCount?: number;             // Shotguns (M3=9, XM1014=6)
  pelletSpreadRad?: number;         // Buckshot cone angle in radians
  shellByShellReload?: boolean;     // Interruptible tube-magazine shell reload
  shellInsertTimeSec?: number;      // Per-shell insert duration
  secondaryAction?: SecondaryActionType;
  burstCount?: number;              // 3 for Glock-18 / FAMAS burst mode
  burstFireRateRpm?: number;        // 1100 RPM for FAMAS burst, 920 RPM for Glock burst
  unsilencedDamageBonus?: number;   // +2 damage when suppressor removed (CS 1.6 M4A1/USP quirk)
  isDualWield?: boolean;            // Dual Elites alternating L/R barrels
  factionRestriction?: 'Vanguard' | 'Syndicate' | 'Any';
}

